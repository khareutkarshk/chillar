#!/usr/bin/env python3
"""The writers' room memory: what landed, what fell flat, and which games are taken — across every reel.

  joke_log.py [--out brand/joke-log.md]

Built from each episode's script reviews (the game line, `## Keep`, notes calling a joke flat / generic /
stock / borrowed) and, once a reel is posted, `notes/retention.md` (audience drops mapped to lines by
retention.py). The scriptwriter and script-reviewer read it on round 1: reuse the *shape* of what worked,
never the line; don't rerun a game; avoid what fell flat twice. Code only — no agent pays to build it.
produce.py rebuilds it before every first draft.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.common import ROOT  # noqa: E402

# recurring desi props/settings — a prop in most recent reels has stopped being specific (comedy.md §4)
# objects/settings: one in most recent reels has stopped being specific. People are a cast, not props — the
# creator wants family and everyday characters (2026-10-21); the log only shows who's been on lately, for variety.
PROPS = ["group chat", "cart", "tapri", "chai", "crush", "Diwali", "mithai", "lifafa", "Sharma ji", "EMI", "forward",
         "OTP", "salary"]
CAST = ["mummy", "papa", "mausi", "chacha", "chachi", "bua", "mamaji", "nani", "dadi", "bhaiya", "didi", "dost", "HR",
        "boss", "landlord", "padosi", "aunty", "uncle"]
FLAT = re.compile(r"\b(flat\w*|generic|stock|weakest|borrowed|dated|mild|doesn't land|does not land|dies|echo)\b", re.I)
MAX_EPISODES, MAX_KEEP, MAX_FLAT, MAX_CHARS = 8, 2, 2, 2800   # it rides in a 24k brief


def reviews(ep: Path) -> list[Path]:
    return sorted((ep / "notes").glob("script-review-*.md"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))


def quote(s: str) -> str:
    m = re.search(r"[\"“]([^\"”]{6,120})[\"”]", s)
    return m.group(1) if m else ""


def episode_entry(ep: Path) -> dict | None:
    rs = reviews(ep)
    if not rs:
        return None
    game, keep, flat = "", [], []
    for r in rs:
        txt = r.read_text()
        if m := re.search(r"^(?:game|Game)[^:\n]*:\s*(.+)$", txt, re.M):
            game = m.group(1).strip()
        for ln in txt.splitlines():
            q = re.sub(r"\s*\[F\d+\]", "", quote(ln)).strip(" .")
            if ln.startswith("- ") and FLAT.search(ln) and len(q) >= 12 and q not in flat:
                flat.append(q)
    last = rs[-1].read_text()
    if m := re.search(r"^## Keep\s*\n(.*?)(?:\n## |\Z)", last, re.S | re.M):
        keep = [q for ln in m.group(1).splitlines() if ln.startswith("- ") and (q := quote(ln) or ln[2:].strip()[:110])]
    flat = [f for f in flat if not any(f in k or k in f for k in keep)]
    drops = []
    ret = ep / "notes" / "retention.md"
    if ret.exists():
        drops = [ln[2:].strip() for ln in ret.read_text().splitlines() if ln.startswith("- ") and "drop" in ln.lower()][:3]
    title = ""
    sc = ep / "script.md"
    if sc.exists() and (m := re.search(r'^title:\s*"?([^"\n]+)', sc.read_text(), re.M)):
        title = m.group(1).strip()
    game = game.strip("*_ ")
    game = game if len(game) <= 150 else game[:147].rsplit(" ", 1)[0] + "…"
    return {"name": ep.name, "title": title, "game": game, "keep": keep[:MAX_KEEP], "flat": flat[:MAX_FLAT],
            "drops": drops}


def build(out: Path) -> str:
    eps = sorted((p for p in (ROOT / "episodes").iterdir() if p.is_dir() and not p.name.startswith("_")),
                 key=lambda p: (p / "script.md").stat().st_mtime if (p / "script.md").exists() else 0, reverse=True)
    entries = [e for p in eps if (e := episode_entry(p))][:MAX_EPISODES]
    lines = ["# Joke log — the writers' room memory (generated by pipeline/joke_log.py; don't edit)", "",
             "Use it on round 1. **Games taken:** don't build a new reel on one of these. **Landed:** reuse the *shape* "
             "(act-out, self-own, callback), never the line. **Fell flat:** don't write that kind of joke again. "
             "**Audience drops** are real Instagram retention — the strongest signal here.", ""]
    scripts = [(p / "script.md").read_text().lower() for p in eps[:6] if (p / "script.md").exists()]
    hot = sorted(((sum(bool(re.search(rf"\b{re.escape(w.lower())}\b", t)) for t in scripts), w) for w in PROPS), reverse=True)
    hot = [f"{w} ({n}/{len(scripts)})" for n, w in hot if n >= max(3, len(scripts) // 2)]
    if hot:
        lines += [f"**Overused lately** (in half or more of the last {len(scripts)} scripts): {', '.join(hot)} — "
                  "lead with a different place/object, or make the moment around it new.", ""]
    cast = sorted(((sum(bool(re.search(rf"\b{re.escape(w.lower())}\b", t)) for t in scripts), w) for w in CAST), reverse=True)
    cast = [f"{w} ({n}/{len(scripts)})" for n, w in cast if n]
    if cast:
        lines += [f"**Cast lately** (characters are welcome — use whoever the story needs): {', '.join(cast)}. "
                  "A regular gets a new moment; a story that needs someone new (bua, landlord, society uncle) gets them.", ""]
    for e in entries:
        lines.append(f"## {e['name']}" + (f" — {e['title']}" if e["title"] else ""))
        if e["game"]:
            lines.append(f"- game taken: {e['game']}")
        lines += [f"- landed: {k}" for k in e["keep"]]
        lines += [f"- fell flat: {f}" for f in e["flat"]]
        lines += [f"- audience: {d}" for d in e["drops"]]
        lines.append("")
    text = "\n".join(lines).rstrip() + "\n"
    if len(text) > MAX_CHARS:                       # drop the oldest reels' blocks, never cut mid-line
        text = text[:MAX_CHARS].rsplit("\n## ", 1)[0].rstrip() + "\n"
    out.write_text(text)
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "brand" / "joke-log.md")
    a = ap.parse_args()
    text = build(a.out)
    print(f"joke log: {a.out.relative_to(ROOT) if a.out.is_relative_to(ROOT) else a.out} ({len(text)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
